import { test } from 'node:test';
import assert from 'node:assert/strict';
import { generateKeyPairSync } from 'node:crypto';
import { mkdtemp, mkdir, rm, writeFile } from 'node:fs/promises';
import { execFileSync, spawnSync } from 'node:child_process';
import { join, resolve } from 'node:path';
import { tmpdir } from 'node:os';
import { DatabaseSync } from 'node:sqlite';
import { publishReviewedFixture } from './fixtures/reviewed-publication.mjs';

const bwrap = spawnSync('bwrap', ['--version'], { stdio: 'ignore' }).status === 0;
test('isolated scripted reviewer signs the actual commit for the fixture publication gate', { skip: process.platform !== 'linux' || !bwrap }, async (t) => {
  const root = await mkdtemp(join(tmpdir(), 'studio-isolated-review-'));
  t.after(() => rm(root, { recursive: true, force: true }));
  const repo = join(root, 'repo'), state = join(root, 'state');
  const id = '12345678-1234-1234-1234-123456789012', worktree = join(repo, '.ai/cezar/worktrees', id);
  await mkdir(repo);
  await mkdir(state);
  const git = (cwd, ...args) => execFileSync('git', args, { cwd, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim();
  git(repo, 'init', '-b', 'main');
  git(repo, 'config', 'user.name', 'Fixture');
  git(repo, 'config', 'user.email', 'fixture@example.invalid');
  await writeFile(join(repo, 'feature.txt'), 'base');
  git(repo, 'add', '.');
  git(repo, 'commit', '-m', 'base');
  await mkdir(join(repo, '.ai/cezar/worktrees'), { recursive: true });
  git(repo, 'worktree', 'add', '-b', 'cez/review-fixture', worktree);
  await writeFile(join(worktree, 'feature.txt'), 'fixture reviewed content');
  git(worktree, 'add', '.');
  git(worktree, 'commit', '-m', 'feature');
  const sha = git(worktree, 'rev-parse', 'HEAD');
  const { publicKey, privateKey } = generateKeyPairSync('ed25519');
  const key = join(root, 'fixture-private-key');
  await writeFile(key, privateKey.export({ type: 'pkcs8', format: 'pem' }), { mode: 0o600 });
  const reviewer = spawnSync('bwrap', ['--unshare-all', '--die-with-parent', '--ro-bind', '/usr', '/usr', '--ro-bind', '/lib', '/lib', '--ro-bind', '/lib64', '/lib64', '--symlink', 'usr/bin', '/bin', '--tmpfs', '/tmp', '--dir', root, '--ro-bind', repo, repo, '--ro-bind', key, '/reviewer-key', '--ro-bind', resolve('studio/fixtures/isolated-reviewer.mjs'), '/reviewer.mjs', '--dev', '/dev', '--proc', '/proc', '--setenv', 'HOME', '/tmp', '--setenv', 'PATH', '/usr/bin:/bin', '--', '/usr/bin/node', '/reviewer.mjs', worktree, id, sha], { env: { PATH: '/usr/bin:/bin' }, encoding: 'utf8', timeout: 15000 });
  assert.equal(reviewer.status, 0, reviewer.stderr);
  const { evidence, signature } = JSON.parse(reviewer.stdout);
  assert.deepEqual(evidence, { runId: id, commit: sha, verdict: 'approve' });
  const db = new DatabaseSync(join(state, 'inbox.sqlite'));
  db.exec('CREATE TABLE receipts (run_id TEXT,status TEXT,source_id TEXT,workflow TEXT)');
  db.prepare('INSERT INTO receipts VALUES (?,?,?,?)').run(id, 'submitted', id, 'studio-feature');
  db.close();
  const run = { id, workflow: 'studio-feature', status: 'done', worktreePath: worktree, branch: 'cez/review-fixture', baseBranch: 'main', graphState: { taken: ['game.pass->qa', 'qa.pass->review', 'review.approve->commit', 'branch_check.pass->done'] } };
  const fetcher = async (url) => Response.json(url.pathname.endsWith('/health') ? { version: '0.20.0', repoRoot: repo } : run);
  let publications = 0;
  const args = { id, url: 'http://127.0.0.1:4321', state, repoRoot: repo, approvedSha: sha, evidence, signature, publicKey, humanApproved: true, fetcher, publisher: () => { publications++; return 'mock-draft'; } };
  await assert.rejects(publishReviewedFixture({ ...args, humanApproved: false }), /explicit human approval/);
  await assert.rejects(publishReviewedFixture({ ...args, signature: undefined }), /trusted review evidence/);
  await assert.rejects(publishReviewedFixture({ ...args, publicKey: generateKeyPairSync('ed25519').publicKey }), /trusted review evidence/);
  assert.equal(publications, 0);
  assert.equal(await publishReviewedFixture(args), 'mock-draft');
  assert.equal(publications, 1);
  await writeFile(join(worktree, 'feature.txt'), 'changed after review');
  git(worktree, 'add', '.');
  git(worktree, 'commit', '-m', 'changed');
  await assert.rejects(publishReviewedFixture(args), /does not match the reviewed/);
  assert.equal(publications, 1);
  console.log('PASS isolated scripted reviewer signed actual commit; missing, untrusted and stale evidence refused without publication');
});
