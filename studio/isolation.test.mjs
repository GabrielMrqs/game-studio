  const root = await mkdtemp(join(existsSync('/tmp/opencode') ? '/tmp/opencode' : tmpdir(), 'studio-isolation-'));
  const main = join(root, 'main'), secret = join(root, 'host-secret');
  const marker = `synthetic-${randomUUID()}`;
