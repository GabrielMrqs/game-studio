import { test } from 'node:test';
import assert from 'node:assert/strict';
import { generateKeyPairSync, randomUUID, sign } from 'node:crypto';
import { chmod, mkdtemp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { execFileSync, spawn } from 'node:child_process';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { DatabaseSync } from 'node:sqlite';
import { createGateway } from './model-gateway.mjs';
import { createIsolationModel } from './fixtures/isolation-model.mjs';
import { publishReviewedFixture } from './fixtures/reviewed-publication.mjs';

test('networkless OpenCode reviewer inspects a commit before fixture signer authorizes it', { timeout: 60000, skip: process.env.STUDIO_TEST_DOCKER_ISOLATION !== '1' }, async (t) => {
  const root = await mkdtemp(join(tmpdir(), 'studio-opencode-review-'));
  const repo = join(root, 'repo'), state = join(root, 'state'), socket = join(root, 'socket');
  const id = '12345678-1234-1234-1234-123456789012', worktree = join(repo, '.ai/cezar/worktrees', id);
  const key = `synthetic-${randomUUID()}`, model = createIsolationModel(key);
  let gateway;
  t.after(async () => {
    if (gateway) await gateway.close();
    if (model.server.listening) await new Promise((done) => model.server.close(done));
    await rm(root, { recursive: true, force: true });
  });
  await mkdir(repo);
  await mkdir(state);
  await mkdir(socket, { mode: 0o777 });
  await chmod(socket, 0o777);
  const git = (cwd, ...args) => execFileSync('git', args, { cwd, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim();
  git(repo, 'init', '-b', 'main');
  git(repo, 'config', 'user.name', 'Fixture');
  git(repo, 'config', 'user.email', 'fixture@example.invalid');
  await writeFile(join(repo, 'feature.txt'), 'base');
  git(repo, 'add', '.');
  git(repo, 'commit', '-m', 'base');
  await mkdir(join(repo, '.ai/cezar/worktrees'), { recursive: true });
  git(repo, 'worktree', 'add', '-b', 'cez/opencode-review', worktree);
  await writeFile(join(worktree, 'feature.txt'), 'fixture reviewed content');
  git(worktree, 'add', '.');
  git(worktree, 'commit', '-m', 'fixture feature');
  const sha = git(worktree, 'rev-parse', 'HEAD');
  const marker = `ISOLATION_TOOL_OK_${sha}`;
  model.setExpectedToolMarker(marker);
  model.setCommand(`test "$(git -C /checkout show ${sha}:feature.txt)" = 'fixture reviewed content' && test ! -e /reviewer-key && ! (printf tamper >> /checkout/feature.txt) 2>/dev/null && printf 'scratch works' > /workspace/agent-output && printf '${marker}\\n'`);
  await new Promise((done) => model.server.listen(0, '127.0.0.1', done));
  gateway = await createGateway({ key, model: 'fixture-model', maxRequests: 10, maxOutputTokens: 64, stateFile: join(root, 'quota.sqlite'), upstream: `http://127.0.0.1:${model.server.address().port}/v1/responses`, initialize: true });
  await new Promise((done) => gateway.server.listen(join(socket, 'model.sock'), done));
  await chmod(join(socket, 'model.sock'), 0o666);
  const { privateKey, publicKey } = generateKeyPairSync('ed25519');
  const image = process.env.STUDIO_ISOLATION_OPENCODE_IMAGE || 'sha256:66619f63e2082168c7746ded83ed84dd604fa2bb3c3498cf5a9c5d2ef24d1b37';
  const args = ['run', '--rm', '--pull=never', '--network=none', '--read-only', '--user=1000:1000', '--cap-drop=ALL', '--security-opt=no-new-privileges', '--pids-limit=128', '--memory=1g', '--tmpfs=/workspace:rw,nosuid,nodev,mode=1777', '--tmpfs=/tmp:rw,nosuid,nodev,mode=1777', '--workdir=/workspace', '--mount', `type=bind,src=${repo},dst=/checkout,readonly`, '--mount', `type=bind,src=${socket},dst=/gateway,readonly`, '--mount', `type=bind,src=${resolve('studio/fixtures/isolation-opencode.mjs')},dst=/fixture/isolation-opencode.mjs,readonly`, '--env', 'HOME=/workspace', '--env', 'TMPDIR=/workspace', '--entrypoint', 'node', image, '/fixture/isolation-opencode.mjs'];
  const child = spawn('docker', args, { env: { PATH: process.env.PATH }, stdio: ['ignore', 'pipe', 'pipe'] });
  let stdout = '', stderr = '';
  child.stdout.on('data', (chunk) => { stdout += chunk; });
  child.stderr.on('data', (chunk) => { stderr += chunk; });
  const code = await new Promise((done, reject) => { child.once('error', reject); child.once('close', done); });
  assert.equal(code, 0, stderr);
  assert.match(stdout, /PASS actual OpenCode shell tool executed synthetic isolation checks via gateway/);
  assert.ok(model.stats().observedTool && model.stats().toolResults > 0 && model.stats().authorized);
  assert.equal(git(worktree, 'rev-parse', 'HEAD'), sha);
  const evidence = { runId: id, commit: sha, verdict: 'approve' };
  const signature = sign(null, Buffer.from(JSON.stringify(evidence)), privateKey).toString('hex');
  const db = new DatabaseSync(join(state, 'inbox.sqlite'));
  db.exec('CREATE TABLE receipts (run_id TEXT,status TEXT,source_id TEXT,workflow TEXT)');
  db.prepare('INSERT INTO receipts VALUES (?,?,?,?)').run(id, 'submitted', id, 'studio-feature');
  db.close();
  const run = { id, workflow: 'studio-feature', status: 'done', worktreePath: worktree, branch: 'cez/opencode-review', baseBranch: 'main', graphState: { taken: ['game.pass->qa', 'qa.pass->review', 'review.approve->commit', 'branch_check.pass->done'] } };
  const fetcher = async (url) => Response.json(url.pathname.endsWith('/health') ? { version: '0.20.0', repoRoot: repo } : run);
  let publications = 0;
  const input = { id, url: 'http://127.0.0.1:4321', state, repoRoot: repo, approvedSha: sha, evidence, signature, publicKey, humanApproved: true, fetcher, publisher: () => { publications++; return 'mock-draft'; } };
  await assert.rejects(publishReviewedFixture({ ...input, humanApproved: false }), /explicit human approval/);
  await assert.rejects(publishReviewedFixture({ ...input, signature: undefined }), /trusted review evidence/);
  await assert.rejects(publishReviewedFixture({ ...input, publicKey: generateKeyPairSync('ed25519').publicKey }), /trusted review evidence/);
  assert.equal(publications, 0);
  assert.equal(await publishReviewedFixture(input), 'mock-draft');
  await writeFile(join(worktree, 'feature.txt'), 'changed after review');
  git(worktree, 'add', '.');
  git(worktree, 'commit', '-m', 'changed');
  await assert.rejects(publishReviewedFixture(input), /does not match the reviewed/);
  assert.equal(publications, 1);
  assert.equal(await readFile(join(repo, 'feature.txt'), 'utf8'), 'base');
  console.log('PASS OpenCode inspected the signed commit via mock gateway; missing, untrusted and stale evidence could not reach mock publisher');
});
