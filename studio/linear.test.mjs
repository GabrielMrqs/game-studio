test('signed Linear webhooks wake paginated polling without duplicating issues', async (t) => {
  const root = await mkdtemp(join(tmpdir(), 'studio-linear-'));
  const issue = { id: '12345678-1234-1234-1234-123456789012', identifier: 'GAME-1', title: 'A lighthouse', description: 'A puzzle', url: 'https://linear.app/x/issue/GAME-1', state: { type: 'unstarted' }, labels: { nodes: [{ name: 'studio' }] } };
  let calls = 0;
  const upstream = createServer(async (req, res) => {
    let raw = '';
    for await (const part of req) raw += part;
    const cursor = JSON.parse(raw).variables.cursor;
    calls++;
    res.setHeader('content-type', 'application/json');
    res.end(JSON.stringify({ data: { team: { issues: { nodes: cursor ? [issue] : [{ ...issue, id: '12345678-1234-1234-1234-123456789013', labels: { nodes: [] } }], pageInfo: { hasNextPage: !cursor, endCursor: cursor ? null : 'next' } } } } }));
  });
  await new Promise((done) => upstream.listen(0, '127.0.0.1', done));
  const adapter = await createAdapter({ inbox: join(root, 'ideas'), state: join(root, 'state'), apiKey: 'test-key', team: 'team', label: 'studio', secret: 'test-secret', endpoint: `http://127.0.0.1:${upstream.address().port}` });
  await new Promise((done) => adapter.server.listen(0, '127.0.0.1', done));
  t.after(async () => { await adapter.close(); await new Promise((done) => upstream.close(done)); await rm(root, { recursive: true, force: true }); });
  await adapter.poll();
  await adapter.poll();
  const files = await readdir(join(root, 'ideas'));
  assert.deepEqual(files, [`linear-${issue.id}.json`]);
  assert.match(JSON.parse(await readFile(join(root, 'ideas', files[0]), 'utf8')).idea, /GAME-1: A lighthouse/);
  const body = JSON.stringify({ type: 'Issue', webhookTimestamp: Date.now() });
  const sig = createHmac('sha256', 'test-secret').update(body).digest('hex');
  const url = `http://127.0.0.1:${adapter.server.address().port}/webhooks/linear`;
  const send = (signature) => fetch(url, { method: 'POST', headers: { 'linear-signature': signature }, body });
  assert.equal((await send('00'.repeat(32))).status, 401);
  assert.equal((await send(sig)).status, 200);
  await adapter.wake();
  assert.ok(calls >= 6);
  assert.equal((await readdir(join(root, 'ideas'))).length, 1);
  assert.equal(verifyWebhook(Buffer.from(body), sig, 'test-secret', Date.now() + 61000), false);
  let submissions = 0;
  const fetcher = async (target) => {
    if (target.pathname.endsWith('/health')) return Response.json({ version: '0.20.0', repoRoot: root });
    submissions++;
    return Response.json({ id: 'fixture-run' }, { status: 201 });
  };
  const args = { inbox: join(root, 'ideas'), state: join(root, 'state'), repoRoot: root, url: 'http://127.0.0.1:4321', fetcher };
  await scan(args);
  await scan(args);
  assert.equal(submissions, 1);
});

test('Linear handoff recovers an interrupted link without letting collisions starve other issues', async (t) => {
  const root = await mkdtemp(join(tmpdir(), 'studio-linear-recovery-'));
  let adapter;
  t.after(async () => { if (adapter) await adapter.close(); await rm(root, { recursive: true, force: true }); });
  const inbox = join(root, 'ideas'), state = join(root, 'state');
  await mkdir(inbox); await mkdir(state);
  const ids = [1, 2, 3, 4].map((n) => `12345678-1234-1234-1234-12345678901${n}`);
  const payloads = ids.map((id) => JSON.stringify({ idea: `Fixture idea ${id}` }));
  const db = new DatabaseSync(join(state, 'linear.sqlite'));
  db.exec('CREATE TABLE issues (id TEXT PRIMARY KEY, payload TEXT NOT NULL, published INTEGER NOT NULL DEFAULT 0)');
  for (let i = 0; i < 3; i++) db.prepare('INSERT INTO issues VALUES (?,?,0)').run(ids[i], payloads[i]);
  db.close();
  const conflictPath = join(inbox, `linear-${ids[0]}.json`);
  await writeFile(conflictPath, JSON.stringify({ idea: 'Different user file' }));
  await writeFile(join(inbox, `linear-${ids[1]}.json`), payloads[1]);
  const outside = join(root, 'outside.json');
  await writeFile(outside, payloads[2]);
  await symlink(outside, join(inbox, `linear-${ids[2]}.json`));
  const issue = { id: ids[3], identifier: 'GAME-4', title: 'Fresh issue', description: 'A fixture', url: 'https://linear.app/fixture/GAME-4', state: { type: 'unstarted' }, labels: { nodes: [{ name: 'studio' }] } };
  const fetcher = async () => Response.json({ data: { team: { issues: { nodes: [issue], pageInfo: { hasNextPage: false, endCursor: null } } } } });
  const options = { inbox, state, apiKey: 'fixture', team: 'fixture', label: 'studio', secret: 'fixture', fetcher };
  adapter = await createAdapter(options);
  await adapter.poll();
  await adapter.close();
  adapter = undefined;
  adapter = await createAdapter(options);
  await adapter.poll();
  const check = new DatabaseSync(join(state, 'linear.sqlite'), { readOnly: true });
  assert.deepEqual(check.prepare('SELECT id,published FROM issues ORDER BY id').all().map((row) => [row.id, row.published]), [[ids[0], 0], [ids[1], 1], [ids[2], 0], [ids[3], 1]]);
  check.close();
  assert.equal(await readFile(conflictPath, 'utf8'), JSON.stringify({ idea: 'Different user file' }));
  assert.equal(await readFile(outside, 'utf8'), payloads[2]);
  assert.ok(!(await readdir(inbox)).some((name) => name.endsWith('.tmp')));
  let submissions = 0;
  const cezar = async (url) => url.pathname.endsWith('/health') ? Response.json({ version: '0.20.0', repoRoot: root }) : Response.json({ id: `fixture-${++submissions}` }, { status: 201 });
  const scanArgs = { inbox, state, repoRoot: root, url: 'http://127.0.0.1:4321', fetcher: cezar };
  await scan(scanArgs);
  await scan(scanArgs);
  assert.equal(submissions, 2);
});
