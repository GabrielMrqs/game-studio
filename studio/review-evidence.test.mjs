import { test } from 'node:test';
import assert from 'node:assert/strict';
import { generateKeyPairSync, sign } from 'node:crypto';
import { mkdtemp, rm, writeFile } from 'node:fs/promises';
import { execFileSync, spawnSync } from 'node:child_process';
import { join, resolve } from 'node:path';
import { tmpdir } from 'node:os';
import { checkReviewEvidence } from './review-evidence.mjs';

test('independent fixture signature binds approval to one run and exact proposed commit', async (t) => {
  const root = await mkdtemp(join(tmpdir(), 'studio-review-evidence-'));
  t.after(() => rm(root, { recursive: true, force: true }));
  const git = (...args) => execFileSync('git', args, { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim();
  git('init', '-b', 'main');
  git('config', 'user.name', 'Fixture');
  git('config', 'user.email', 'fixture@example.invalid');
  await writeFile(join(root, 'feature'), 'reviewed');
  git('add', '.');
  git('commit', '-m', 'reviewed');
  const reviewed = git('rev-parse', 'HEAD');
  const runId = '12345678-1234-1234-1234-123456789012';
  const { privateKey, publicKey } = generateKeyPairSync('ed25519');
  const otherKey = generateKeyPairSync('ed25519');
  const evidence = { runId, commit: reviewed, verdict: 'approve' };
  const signature = sign(null, Buffer.from(JSON.stringify(evidence)), privateKey).toString('hex');
  const args = { evidence, signature, publicKey, runId, commit: reviewed };
  assert.equal(checkReviewEvidence(args), true);
  assert.equal(checkReviewEvidence({ ...args, publicKey: publicKey.export({ type: 'spki', format: 'pem' }) }), true);
  assert.equal(checkReviewEvidence({ ...args, publicKey: 'not a key' }), false);
  assert.equal(checkReviewEvidence({ ...args, publicKey: otherKey.publicKey }), false);
  assert.equal(checkReviewEvidence({ ...args, signature: '0'.repeat(128) }), false);
  assert.equal(checkReviewEvidence({ ...args, runId: '12345678-1234-1234-1234-123456789013' }), false);
  assert.equal(checkReviewEvidence({ ...args, evidence: { ...evidence, verdict: 'changes' } }), false);
  await writeFile(join(root, 'feature'), 'changed after review');
  git('add', '.');
  git('commit', '-m', 'changed');
  assert.equal(checkReviewEvidence({ ...args, commit: git('rev-parse', 'HEAD') }), false);
  const cli = spawnSync(process.execPath, [resolve('studio/publish-run.mjs'), runId], { cwd: root, env: { PATH: process.env.PATH }, encoding: 'utf8' });
  assert.notEqual(cli.status, 0);
  assert.match(cli.stderr, /RUN_ID --approve/);
});
