import { test } from 'node:test';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { mkdtemp, mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { execFileSync, spawnSync } from 'node:child_process';
import { DatabaseSync } from 'node:sqlite';
import { inspectRecovery } from './inspect-recovery.mjs';

test('read-only inspection correlates an interrupted run, session, worktree and receipt', async (t) => {
  const root = await mkdtemp(join(tmpdir(), 'studio-inspect-'));
  t.after(() => rm(root, { recursive: true, force: true }));
  for (const args of [['init', '-b', 'main'], ['config', 'user.name', 'Fixture'], ['config', 'user.email', 'fixture@example.invalid'], ['commit', '--allow-empty', '-m', 'fixture']]) execFileSync('git', args, { cwd: root, stdio: 'ignore' });
  const id = '12345678-1234-1234-1234-123456789012', marker = '12345678-1234-1234-1234-123456789013';
  const idea = 'sensitive fixture idea', state = join(root, 'state'), path = join(root, '.ai/cezar/worktrees', id);
  await mkdir(join(root, '.ai/cezar/worktrees'), { recursive: true });
  await mkdir(state);
  execFileSync('git', ['worktree', 'add', '-b', 'fixture-branch', path], { cwd: root, stdio: 'ignore' });
  const run = { id, status: 'running', workflow: 'studio-feature', branch: 'fixture-branch', worktreePath: path, task: `${idea}\n\n[studio-receipt:${marker}]`, steps: [{ id: 'gameplay', backend: 'opencode', sessionId: 'ses_fixture123' }] };
  const index = join(root, '.ai/cezar/runs.json');
  await writeFile(index, JSON.stringify([run]));
  const database = join(state, 'inbox.sqlite'), db = new DatabaseSync(database);
  db.exec('CREATE TABLE receipts(hash TEXT, status TEXT, run_id TEXT, source_id TEXT, workflow TEXT, marker TEXT, conflicting_run_id TEXT, detail TEXT)');
  db.prepare('INSERT INTO receipts VALUES (?,?,?,?,?,?,?,?)').run(createHash('sha256').update(idea).digest('hex'), 'submitted', id, marker, 'studio-feature', marker, null, 'private fixture detail');
  db.close();
  const beforeIndex = await readFile(index), beforeDb = await readFile(database), beforeFiles = await readdir(state);
  const report = await inspectRecovery({ id, repoRoot: root, state });
  assert.deepEqual(report.run, { id, status: 'running', workflow: 'studio-feature' });
  assert.deepEqual(report.sessions, { recorded: [{ step: 'gameplay', backend: 'opencode', session_id: 'ses_fixture123' }], opencode_store: 'not_checked' });
  assert.equal(report.worktree.state, 'registered');
  assert.equal(report.worktree.branch_matches, true);
  assert.deepEqual(report.receipts.matches, [{ role: 'primary', status: 'submitted', workflow_matches: true, task_matches: true, linear_issue_id: marker }]);
  assert.ok(!JSON.stringify(report).includes(idea));
  assert.ok(!JSON.stringify(report).includes('private fixture detail'));
  assert.deepEqual(await readFile(index), beforeIndex);
  assert.deepEqual(await readFile(database), beforeDb);
  assert.deepEqual(await readdir(state), beforeFiles);
  const cli = spawnSync(process.execPath, [resolve('studio/inspect-recovery.mjs'), id], { cwd: root, env: { PATH: process.env.PATH, STUDIO_STATE: state }, encoding: 'utf8' });
  assert.equal(cli.status, 0, cli.stderr);
  assert.equal(JSON.parse(cli.stdout).receipts.matches[0].task_matches, true);
  for (const uncertain of [{ ...run, branch: undefined }, { ...run, status: 'unknown' }]) {
    await writeFile(index, JSON.stringify([uncertain]));
    const result = spawnSync(process.execPath, [resolve('studio/inspect-recovery.mjs'), id], { cwd: root, env: { PATH: process.env.PATH, STUDIO_STATE: state }, encoding: 'utf8' });
    assert.equal(result.status, 1);
    const output = JSON.parse(result.stdout);
    assert.equal(output.worktree.state, 'registered');
    if (!uncertain.branch) assert.equal(output.worktree.branch_matches, undefined);
    else assert.equal(output.run.status, 'unrecognized');
  }
  await writeFile(index, beforeIndex);
  const approve = spawnSync(process.execPath, [resolve('studio/publish-run.mjs'), id], { cwd: root, env: { PATH: process.env.PATH }, encoding: 'utf8' });
  assert.notEqual(approve.status, 0);
  assert.match(approve.stderr, /--approve/);
  const pending = new DatabaseSync(database);
  pending.prepare("UPDATE receipts SET status='pending', run_id=NULL").run();
  pending.close();
  const pendingReport = await inspectRecovery({ id, repoRoot: root, state });
  assert.equal(pendingReport.receipts.matches[0].role, 'marker_only');
  assert.equal(pendingReport.receipts.matches[0].task_matches, true);
  const inspectCli = () => spawnSync(process.execPath, [resolve('studio/inspect-recovery.mjs'), id], { cwd: root, env: { PATH: process.env.PATH, STUDIO_STATE: state }, encoding: 'utf8' });
  const pendingCli = inspectCli();
  assert.equal(pendingCli.status, 1);
  assert.equal(JSON.parse(pendingCli.stdout).receipts.matches[0].role, 'marker_only');
  const changed = new DatabaseSync(database);
  changed.prepare("UPDATE receipts SET status='conflict', run_id=?").run(id);
  changed.close();
  const conflict = inspectCli();
  assert.equal(conflict.status, 1);
  assert.equal(JSON.parse(conflict.stdout).receipts.matches[0].status, 'conflict');
  const missing = new DatabaseSync(database);
  missing.exec('DELETE FROM receipts');
  missing.close();
  const noReceipt = inspectCli();
  assert.equal(noReceipt.status, 1);
  assert.deepEqual(JSON.parse(noReceipt.stdout).receipts.matches, []);
});

test('inspection reports ambiguous, mismatched and unavailable state without repairing it', async (t) => {
  const root = await mkdtemp(join(tmpdir(), 'studio-inspect-errors-'));
  t.after(() => rm(root, { recursive: true, force: true }));
  const id = '12345678-1234-1234-1234-123456789012', other = '12345678-1234-1234-1234-123456789013';
  const state = join(root, 'state'), index = join(root, '.ai/cezar/runs.json');
  await mkdir(join(root, '.ai/cezar/worktrees', id), { recursive: true });
  await mkdir(state);
  const run = { id, status: 'queued', workflow: 'studio-plan', task: 'private', steps: [{ id: 'plan', backend: 'opencode', sessionId: 'untrusted secret' }] };
  await writeFile(index, JSON.stringify([run]));
  let result = await inspectRecovery({ id, repoRoot: root, state });
  assert.equal(result.worktree.state, 'not_recorded');
  assert.equal(result.worktree.expected_path_exists, true);
  assert.equal(result.sessions.recorded[0].session_id, null);
  assert.equal(result.receipts.state, 'unavailable');
  assert.deepEqual(await readdir(state), []);
  run.worktreePath = '/outside/private-path';
  await writeFile(index, JSON.stringify([run]));
  result = await inspectRecovery({ id, repoRoot: root, state });
  assert.equal(result.worktree.state, 'path_mismatch');
  assert.ok(!JSON.stringify(result).includes('/outside/private-path'));
  assert.ok(!JSON.stringify(result).includes('untrusted secret'));
  const db = new DatabaseSync(join(state, 'inbox.sqlite'));
  db.exec('CREATE TABLE receipts(hash TEXT, status TEXT, run_id TEXT, source_id TEXT, workflow TEXT, marker TEXT, conflicting_run_id TEXT)');
  db.prepare('INSERT INTO receipts VALUES (?,?,?,?,?,?,?)').run('a'.repeat(64), 'conflict', other, null, 'studio-feature', other, id);
  db.close();
  result = await inspectRecovery({ id, repoRoot: root, state });
  assert.deepEqual(result.receipts.matches, [{ role: 'conflicting', status: 'conflict', workflow_matches: false, task_matches: false, linear_issue_id: null }]);
  await writeFile(join(state, 'inbox.sqlite-wal'), 'fixture uncheckpointed state');
  result = await inspectRecovery({ id, repoRoot: root, state });
  assert.equal(result.receipts.state, 'unavailable_active_or_uncheckpointed_database');
  assert.equal(await readFile(join(state, 'inbox.sqlite-wal'), 'utf8'), 'fixture uncheckpointed state');
  await writeFile(index, JSON.stringify([run, run]));
  await assert.rejects(inspectRecovery({ id, repoRoot: root, state }), /missing or ambiguous/);
  await assert.rejects(inspectRecovery({ id: '../unsafe', repoRoot: root, state }), /invalid run ID/);
});
