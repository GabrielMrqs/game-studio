import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, writeFile, rm } from 'node:fs/promises';
import { createServer } from 'node:http';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { execFileSync } from 'node:child_process';
import { DatabaseSync } from 'node:sqlite';
import { publish } from './publish.mjs';

test('pushes only a feature branch, creates draft PR and reports to Linear once', async (t) => {
  const root = await mkdtemp(join(tmpdir(), 'studio-publish-'));
  const repo = join(root, 'repo'), remote = join(root, 'remote.git');
  await mkdir(repo);
  const run = (cwd, ...args) => execFileSync('git', args, { cwd, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim();
  run(root, 'init', '--bare', remote);
  run(repo, 'init', '-b', 'main');
  run(repo, 'config', 'user.name', 'Test');
  run(repo, 'config', 'user.email', 'test@example.invalid');
  await writeFile(join(repo, 'feature'), 'base');
  run(repo, 'add', '.');
  run(repo, 'commit', '-m', 'base');
  const main = run(repo, 'rev-parse', 'HEAD');
  run(repo, 'push', remote, 'main:main');
  run(repo, 'remote', 'add', 'origin', 'https://github.com/acme/game.git');
  run(repo, 'switch', '-c', 'cez/fixture');
  await writeFile(join(repo, 'feature'), 'new');
  run(repo, 'add', '.');
  run(repo, 'commit', '-m', 'feature');
  const requests = [];
  let failLinear = false;
  const server = createServer(async (req, res) => {
    let body = '';
    for await (const chunk of req) body += chunk;
    requests.push({ method: req.method, url: req.url, body: body && JSON.parse(body) });
    res.setHeader('content-type', 'application/json');
    if (req.method === 'GET') res.end('[]');
    else if (req.url.startsWith('/repos/')) { res.statusCode = 201; res.end(JSON.stringify({ draft: true, html_url: 'https://github.com/acme/game/pull/42' })); }
    else if (failLinear) { res.statusCode = 503; res.end('{}'); }
    else res.end(JSON.stringify({ data: { commentCreate: { success: true } } }));
  });
  await new Promise((done) => server.listen(0, '127.0.0.1', done));
  t.after(async () => { await new Promise((done) => server.close(done)); await rm(root, { recursive: true, force: true }); });
  const fetcher = (url, options) => fetch(`http://127.0.0.1:${server.address().port}${new URL(url).pathname}${new URL(url).search}`, options);
  await mkdir(join(root, 'state'));
  const legacy = new DatabaseSync(join(root, 'state/publish.sqlite'));
  legacy.exec("CREATE TABLE publications (repo TEXT NOT NULL, branch TEXT NOT NULL, issue TEXT NOT NULL, sha TEXT NOT NULL, phase TEXT NOT NULL, pr_url TEXT, PRIMARY KEY(repo,branch)); INSERT INTO publications VALUES ('acme/game','cez/old','old-issue','old-sha','claimed',NULL)");
  legacy.close();
  const options = { worktree: repo, state: join(root, 'state'), repo: 'acme/game', base: 'main', issue: '12345678-1234-1234-1234-123456789012', title: 'Fixture change', githubToken: 'fixture', linearKey: 'fixture', approvedSha: run(repo, 'rev-parse', 'HEAD'), fetcher, push: async ({ sha, branch }) => run(repo, 'push', remote, `${sha}:refs/heads/${branch}`) };
  await assert.rejects(publish({ ...options, approvedSha: '0'.repeat(40) }), /reviewed commit SHA/);
  assert.equal(requests.length, 0);
  await writeFile(join(repo, 'feature'), 'changed after review');
  run(repo, 'add', '.');
  run(repo, 'commit', '-m', 'changed after review');
  await assert.rejects(publish(options), /reviewed commit SHA/);
  assert.equal(requests.length, 0);
  options.approvedSha = run(repo, 'rev-parse', 'HEAD');
  assert.equal(await publish(options), 'https://github.com/acme/game/pull/42');
  const receipts = new DatabaseSync(join(root, 'state/publish.sqlite'), { readOnly: true });
  assert.equal(receipts.prepare("SELECT base_branch FROM publications WHERE branch='cez/fixture'").get().base_branch, 'main');
  assert.equal(receipts.prepare("SELECT base_branch FROM publications WHERE branch='cez/old'").get().base_branch, null);
  receipts.close();
  assert.equal(run(root, '--git-dir', remote, 'rev-parse', 'refs/heads/main'), main);
  assert.equal(run(root, '--git-dir', remote, 'rev-parse', 'refs/heads/cez/fixture'), run(repo, 'rev-parse', 'HEAD'));
  assert.equal(requests[1].body.draft, true);
  assert.match(requests[2].body.variables.input.body, /pull\/42/);
  await assert.rejects(publish(options), /already claimed/);
  assert.equal(requests.length, 3);
  run(repo, 'switch', 'main');
  await assert.rejects(publish({ ...options, state: join(root, 'other') }), /only a cez/);
  run(repo, 'switch', '-c', 'cez/failure');
  await writeFile(join(repo, 'feature'), 'another change');
  run(repo, 'add', '.');
  run(repo, 'commit', '-m', 'second feature');
  options.approvedSha = run(repo, 'rev-parse', 'HEAD');
  failLinear = true;
  await assert.rejects(publish(options), /Linear comment failed or uncertain/);
  await assert.rejects(publish(options), /already claimed/);
  assert.equal(requests.length, 6);
});
